class Command(BaseCommand):
    help = 'Create clearly labelled sample listings and a local demo account.'

    @transaction.atomic
    def handle(self, *args, **options):
        User = get_user_model()
        demo_user, user_created = User.objects.get_or_create(
            email='demo@example.test',
            defaults={
                'first_name': 'Demo',
                'last_name': 'Account',
                'is_verified': True,
                'is_active': True,
            },
        )
        demo_password = None
        if user_created:
            demo_password = secrets.token_urlsafe(24)
            demo_user.set_password(demo_password)
            demo_user.save(update_fields=['password'])

        created_count = 0
        for details in DEMO_PROPERTIES:
            listing, created = PropertyListing.objects.get_or_create(
                title=details['title'],
                city=details['city'],
                locality=details['locality'],
                defaults={
                    **details,
                    'address': f'Demo address · {details["locality"]}, {details["city"]}',
                    'pincode': '281121' if details['city'] == 'Vrindavan' else '281001',
                    'owner': demo_user,
                    'status': 'Active',
                },
            )
            if created:
                created_count += 1
            elif listing.status != 'Active':
                listing.status = 'Active'
                listing.save(update_fields=['status'])

        self.stdout.write(self.style.SUCCESS(
            f'Demo seed complete: {created_count} listings added; '
            f'{len(DEMO_PROPERTIES)} demo listings available.'
        ))
        self.stdout.write('Demo sign-in email: demo@example.test')
        if demo_password:
            self.stdout.write(f'Demo sign-in password (generated for this local DB): {demo_password}')
        else:
            self.stdout.write(
                'Demo account already existed; its password was left unchanged. '
                'Use the password set when that account was created.'
            )
        self.stdout.write(self.style.WARNING(
            'All generated listings and contact details are fictional demo data; do not publish them.'
        ))
